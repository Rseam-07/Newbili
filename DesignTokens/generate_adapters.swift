#!/usr/bin/env swift

import Foundation

enum GeneratorError: LocalizedError {
    case usage
    case missingValue(String)

    var errorDescription: String? {
        switch self {
        case .usage:
            return "Usage: swift generate_adapters.swift <tokens.json> <swift-output> [kotlin-output]"
        case .missingValue(let path):
            return "Missing or invalid token value at \(path)"
        }
    }
}

struct TokenReader {
    let root: [String: Any]

    func number(_ path: String) throws -> Double {
        let token = try object(at: path)
        guard let value = token["$value"] as? [String: Any],
              let number = value["value"] as? NSNumber
        else { throw GeneratorError.missingValue(path) }
        return number.doubleValue
    }

    func cubicBezier(_ path: String) throws -> [Double] {
        let token = try object(at: path)
        guard let values = token["$value"] as? [NSNumber], values.count == 4 else {
            throw GeneratorError.missingValue(path)
        }
        return values.map(\.doubleValue)
    }

    private func object(at path: String) throws -> [String: Any] {
        var current: Any = root
        for component in path.split(separator: ".").map(String.init) {
            guard let object = current as? [String: Any], let next = object[component] else {
                throw GeneratorError.missingValue(path)
            }
            current = next
        }
        guard let result = current as? [String: Any] else {
            throw GeneratorError.missingValue(path)
        }
        return result
    }
}

func literal(_ value: Double) -> String {
    if value.rounded() == value { return String(format: "%.1f", value) }
    return String(format: "%.4g", value)
}

func durationLiteral(milliseconds: Double) -> String {
    String(format: "%.4g", milliseconds / 1_000)
}

let arguments = CommandLine.arguments
guard arguments.count == 3 || arguments.count == 4 else {
    throw GeneratorError.usage
}

