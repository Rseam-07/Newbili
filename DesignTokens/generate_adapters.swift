let data = try Data(contentsOf: tokenURL)
guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
    throw GeneratorError.missingValue("root")
}
let tokens = TokenReader(root: root)
let curve = try tokens.cubicBezier("global.motionCurve.standard")

